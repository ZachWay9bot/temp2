def trig(angle):
    angle &= 0xffff
    q=(((angle+0x8000)&0xffff)>>6)&0x300
    i=(angle>>6)&0xff; j=0xff-i
    if q==0x000: hi=-QTR[i]; lo=-QTR[j]
    elif q==0x100: hi=-QTR[j]; lo=QTR[i]
    elif q==0x200: hi=QTR[i]; lo=QTR[j]
    else: hi=QTR[j]; lo=-QTR[i]
    def s16(x):
        x &= 0xffff
        return x-0x10000 if x&0x8000 else x
    return s16(lo),s16(hi)

