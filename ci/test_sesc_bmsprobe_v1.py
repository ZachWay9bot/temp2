# Check the exact read frames generated by the probe matrix.
def frame(reg,ask):
    out=[0x5A,0xA5,0x01,0x20,0x22,0x01,reg,ask,0,0]
    ck=(~sum(out[2:8]))&0xffff
    out[8]=ck&0xff
    out[9]=(ck>>8)&0xff
    return out

expected={
    (0x10,16): [0x5A,0xA5,0x01,0x20,0x22,0x01,0x10,0x10,0x9B,0xFF],
    (0x17, 2): [0x5A,0xA5,0x01,0x20,0x22,0x01,0x17,0x02,0xA2,0xFF],
    (0x30,12): [0x5A,0xA5,0x01,0x20,0x22,0x01,0x30,0x0C,0x7F,0xFF],
    (0x34, 2): [0x5A,0xA5,0x01,0x20,0x22,0x01,0x34,0x02,0x85,0xFF],
    (0x40,20): [0x5A,0xA5,0x01,0x20,0x22,0x01,0x40,0x14,0x67,0xFF],
}
for k,v in expected.items():
    assert frame(*k)==v,(k,frame(*k),v)

